#: Capability matrix (#2001): the four statuses and three evidence kinds the
#: validation rules are written against; the registry legend must match them.
CAP_STATUSES = ("supported", "partial", "unsupported", "unverified")
CAP_EVIDENCE_KINDS = ("live", "registry", "repo")
#: Statuses that claim something and therefore need evidence / a justification.
_CAP_NEEDS_EVIDENCE = ("supported", "partial")
_CAP_NEEDS_REASON = ("partial", "unsupported")


def _cap_rows(caps: dict[str, Any]) -> list[dict[str, Any]]:
    return [row for group in caps.get("groups") or [] for row in group.get("rows") or []]


def _cap_cells(caps: dict[str, Any], client_id: str) -> dict[str, dict[str, Any]]:
    return {cell.get("row"): cell for cell in (caps.get("cells") or {}).get(client_id) or []}


def _issue_links(issues: Iterable[int], repo_url: str) -> str:
    return ", ".join(f"[#{n}]({repo_url}/issues/{n})" for n in issues)


def _cell_text(text: str) -> str:
    """Keep a note inside one markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ")


def validate_capabilities(registry: dict[str, Any]) -> list[str]:
    """Guard the ``capabilities`` section: nothing is claimed without evidence."""
    caps = registry.get("capabilities")
    if not isinstance(caps, dict):
        return ["capabilities: section missing"]
    problems: list[str] = []
    legend = [entry.get("status") for entry in caps.get("legend") or []]
    _expect(
        legend == list(CAP_STATUSES),
        f"capabilities.legend: statuses must be {list(CAP_STATUSES)}, got {legend}",
        problems,
    )
    kinds = [entry.get("kind") for entry in caps.get("evidence_kinds") or []]
    _expect(
        kinds == list(CAP_EVIDENCE_KINDS),
        f"capabilities.evidence_kinds: must be {list(CAP_EVIDENCE_KINDS)}, got {kinds}",
        problems,
    )
    verified = caps.get("verified") or {}
    for field in ("date", "server", "plugin"):
        _expect(bool(verified.get(field)), f"capabilities.verified: missing {field}", problems)
    _expect(
        len(caps.get("notes_de") or []) == len(caps.get("notes_en") or []),
        "capabilities: notes_de/notes_en differ in length",
        problems,
    )

    row_keys: set[str] = set()
    for row in _cap_rows(caps):
        key = row.get("key")
        _expect(key not in row_keys, f"capabilities: duplicate row {key!r}", problems)
        row_keys.add(key)
        for lang in ("de", "en"):
            _expect(bool(row.get(f"label_{lang}")), f"capabilities: row {key!r} lacks label_{lang}", problems)

    client_ids = {client["id"] for client in registry["clients"]}
    for client_id, cells in (caps.get("cells") or {}).items():
        if client_id not in client_ids:
            problems.append(f"capabilities: unknown client id {client_id!r}")
            continue
        seen: set[str] = set()
        for cell in cells or []:
            row = cell.get("row")
            where = f"capabilities.{client_id}.{row}"
            if row not in row_keys:
                problems.append(f"{where}: unknown row key")
            if row in seen:
                problems.append(f"{where}: duplicate row")
            seen.add(row)
            status = cell.get("status")
            if status not in CAP_STATUSES:
                problems.append(f"{where}: unknown status {status!r}")
                continue
            evidence = cell.get("evidence") or {}
            if evidence:
                _expect(
                    evidence.get("kind") in CAP_EVIDENCE_KINDS,
                    f"{where}: unknown evidence kind {evidence.get('kind')!r}",
                    problems,
                )
            if status in _CAP_NEEDS_EVIDENCE:
                _expect(
                    bool(evidence.get("kind") and evidence.get("detail")),
                    f"{where}: {status} needs evidence (kind + detail)",
                    problems,
                )
            has_note = bool(cell.get("note_de") and cell.get("note_en"))
            if status in _CAP_NEEDS_REASON:
                _expect(
                    bool(cell.get("issues")) or has_note,
                    f"{where}: {status} needs an issue or an explanatory note",
                    problems,
                )
            _expect(
                bool(cell.get("note_de")) == bool(cell.get("note_en")),
                f"{where}: note needs both note_de and note_en",
                problems,
            )
    return problems


def render_capabilities(registry: dict[str, Any], *, lang: str) -> str:
    """Render the client capability matrix (#2001). Missing cells are ``?``."""
    de = lang == "de"
    caps = registry["capabilities"]
    clients = registry["clients"]
    repo_url = registry["store"]["mcp_registry"]["repository_url"]
    symbol = {entry["status"]: entry["symbol"] for entry in caps["legend"]}
    verified = caps["verified"]
    unverified = {"status": "unverified"}

    parts: list[str] = [
        GENERATED_HEADER,
        "",
        "# ReqogniLoom — Client-Capability-Matrix" if de else "# ReqogniLoom — client capability matrix",
        "",
        (
            f"> Verifiziert am {verified['date']} gegen den ReqogniLoom-Server "
            f"{verified['server']} und den Repository-Stand mit Plugin {verified['plugin']}."
            if de
            else f"> Verified on {verified['date']} against ReqogniLoom server "
            f"{verified['server']} and the repository state at plugin {verified['plugin']}."
        ),
        "",
        (
            "Datum und Versionen beziehen sich auf diesen Verifikationslauf, nicht auf das "
            "aktuelle Release. Die Client-Version und die Art des Nachweises stehen je Zelle "
            "in den Detailtabellen. Die Seite ist aus `clients/registry.yaml` generiert."
            if de
            else "The date and versions refer to this verification run, not to the current "
            "release. The client version and the kind of evidence are given per cell in the "
            "detail tables. This page is generated from `clients/registry.yaml`."
        ),
        "",
        "## " + ("Legende" if de else "Legend"),
        "",
        "| Symbol | Status | " + ("Bedeutung" if de else "Meaning") + " |",
        "|---|---|---|",
    ]
    for entry in caps["legend"]:
        parts.append(
            f"| {entry['symbol']} | `{entry['status']}` | {entry['label_de' if de else 'label_en']} |"
        )
    parts += ["", "**" + ("Nachweisarten" if de else "Evidence kinds") + ":**", ""]
    parts += [
        f"- `{entry['kind']}`: {entry['label_de' if de else 'label_en']}"
        for entry in caps["evidence_kinds"]
    ]

    cells = {client["id"]: _cap_cells(caps, client["id"]) for client in clients}
    parts += [
        "",
        "## Matrix",
        "",
        "| " + ("Funktion / Artefakt" if de else "Feature / artifact") + " | "
        + " | ".join(client["name"] for client in clients) + " |",
        "|---|" + "---|" * len(clients),
    ]
    for group in caps["groups"]:
        parts.append(f"| **{group['title_de' if de else 'title_en']}** |" + " |" * len(clients))
        for row in group["rows"]:
            marks = [
                symbol[cells[client["id"]].get(row["key"], unverified)["status"]]
                for client in clients
            ]
            parts.append(f"| {row['label_de' if de else 'label_en']} | " + " | ".join(marks) + " |")

    parts += ["", "## " + ("Details je Client" if de else "Details per client"), ""]
    head = (
        "| Funktion / Artefakt | Status | Hinweis | Nachweis | Issues |"
        if de
        else "| Feature / artifact | Status | Note | Evidence | Issues |"
    )
    for client in clients:
        parts += [f"### {client['name']}", "", head, "|---|---|---|---|---|"]
        for row in _cap_rows(caps):
            cell = cells[client["id"]].get(row["key"], unverified)
            evidence = cell.get("evidence") or {}
            proof = f"`{evidence['kind']}` ({evidence['detail']})" if evidence else "—"
            parts.append(
                f"| {row['label_de' if de else 'label_en']} "
                f"| {symbol[cell['status']]} `{cell['status']}` "
                f"| {_cell_text(cell.get('note_de' if de else 'note_en') or '—')} "
                f"| {proof} "
                f"| {_issue_links(cell.get('issues') or [], repo_url) or '—'} |"
            )
        parts.append("")

    parts += ["## " + ("Hinweise" if de else "Notes"), ""]
    parts += [f"{i}. {note}" for i, note in enumerate(caps["notes_de" if de else "notes_en"], 1)]
    return "\n".join(parts).rstrip("\n") + "\n"


def render_marketplace(registry: dict[str, Any], version: str) -> str:
    """Render the repo-root Claude Code marketplace (Stufe 2, store S2, E3).

    The marketplace lives in this repository (plan §5.1); ``source`` is the
    ``git-subdir`` form so ``claude plugin marketplace add Popoboxxo/ReqogniLoom``
    resolves the plugin directory inside the repo instead of needing a second
    repository.
    """
    store = registry["store"]["marketplace"]
    manifest = {
        "name": store["name"],
        "owner": store["owner"],
        "description": store["description"],
        "version": version,
        "plugins": [
            {
                "name": store["plugin"],
                "source": {
                    "source": "git-subdir",
                    "url": store["repo"],
                    "path": store["plugin_path"],
                },
                "description": store["plugin_description"],
                "version": version,
            }
        ],
    }
    return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"


def render_server_json(registry: dict[str, Any], version: str) -> str:
    """Render the repo-root MCP registry entry (Stufe 2, store S1).

    Conforms to ``server.schema.json`` (2025-12-11): a primary Streamable HTTP
    remote with an ``X-API-Key`` env-var template (never a literal key), plus —
    since #1913 — the still-served legacy SSE remote marked deprecated in its
    host-variable description. E1 is confirmed (user, 2026-10-09): personal
    namespace ``io.github.popoboxxo``.
    """
    mcp = registry["store"]["mcp_registry"]
    headers = [
        {
            "name": mcp["auth_header"],
            "value": "{REQOGNILOOM_API_KEY}",
            "isSecret": True,
            "isRequired": True,
        }
    ]
    remotes: list[dict[str, Any]] = [
        {
            "type": "streamable-http",
            "url": f"https://{{host}}{mcp['remote_path']}",
            "variables": {
                "host": {
                    "description": "Hostname of your self-hosted ReqogniLoom instance",
                    "isRequired": True,
                }
            },
            "headers": headers,
        }
    ]
    # #1913: publish the still-served legacy SSE transport as a second remote.
    # The MCP server schema has no `deprecated` field, so the explicit target
    # statement lives in the host variable's description (and in the generated
    # client docs via conventions.transport_rule_*). New configs use /mcp/.
    legacy_path = mcp.get("legacy_remote_path")
    if legacy_path:
        remotes.append(
            {
                "type": "sse",
                "url": f"https://{{host}}{legacy_path}",
                "variables": {
                    "host": {
                        "description": (
                            "Hostname of your self-hosted ReqogniLoom instance "
                            "(legacy SSE transport — DEPRECATED, do not use for "
                            "new configs; prefer /mcp/ streamable-http)"
                        ),
                        "isRequired": True,
                    }
                },
                "headers": headers,
            }
        )
    server = {
        "$schema": SERVER_SCHEMA,
        "name": mcp["name"],
        "description": mcp["description"],
        "version": version,
        "repository": {"url": mcp["repository_url"], "source": "github"},
        "remotes": remotes,
    }
    return json.dumps(server, indent=2, ensure_ascii=False) + "\n"


def _expect(condition: bool, message: str, problems: list[str]) -> None:
    if not condition:
        problems.append(message)


def validate_artifacts(registry: dict[str, Any]) -> list[str]:
    """Lightweight registry <-> shipped-artifact guard.

    Proves that every referenced config artifact exists, carries the registry's
    transport path, and never embeds a literal ``reqlo_`` key. The deep parity
    checks live in ``dist/test_mcp_convention_parity.py``; this is the link from
    the single source of truth to those artifacts.
    """
    problems: list[str] = []
    conv = registry["conventions"]
    for client in registry["clients"]:
        artifact = client.get("config_artifact") or ""
        if not artifact:
            continue
        path = REPO_ROOT / artifact
        _expect(path.is_file(), f"{client['id']}: missing config artifact {artifact}", problems)
        if not path.is_file():
            continue
        raw = path.read_text(encoding="utf-8")
        if client.get("url_path"):
            _expect(
                client["url_path"] in raw,
                f"{client['id']}: {artifact} does not contain transport path "
                f"{client['url_path']}",
                problems,
            )
        # Comments may legitimately spell the documented ``reqlo_…`` hint;
        # only a literal key in an actual config value is a leak.
        non_comment = [
            line
            for line in raw.splitlines()
            if not line.lstrip().startswith(("#", "//"))
        ]
        _expect(
            conv["api_key_prefix"] not in "\n".join(non_comment),
            f"{client['id']}: {artifact} embeds a literal {conv['api_key_prefix']} key",
            problems,
        )
    return problems


#: ``server.schema.json`` (2025-12-11) name pattern, exactly one slash.
_SERVER_NAME_RE = re.compile(r"^[a-zA-Z0-9.-]+/[a-zA-Z0-9._-]+$")

#: A concrete version only — ranges (``^``/``~``/``>``) and ``latest`` are
#: forbidden in the version-coupled store artifacts.
_VERSION_RE = re.compile(r"^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$")


def validate_store_artifacts(
    registry: dict[str, Any], files: dict[Path, str]
) -> list[str]:
    """Guard the Stufe-2 artifacts: version == ``VERSION`` and schema-lite facts.

    Runs against the generated content (not the committed files), so a wrong
    version baked into a render function is caught here as well as by the
    ``--check`` stale comparison of the committed files.
    """
    problems: list[str] = []
    version = load_version()
    store = registry.get("store") or {}

    _expect(
        bool(_VERSION_RE.match(version)),
        f"VERSION {version!r} is not a concrete version (ranges/'latest' are forbidden)",
        problems,
    )

    market_raw = files.get(MARKETPLACE_PATH)
    if market_raw is None:
        problems.append("marketplace.json is not planned by plan_outputs()")
    else:
        market = _load_json(market_raw, MARKETPLACE_PATH.name, problems)
        if isinstance(market, dict):
            market_meta = store.get("marketplace") or {}
            _expect(
                market.get("name") == market_meta.get("name"),
                f"marketplace.json: name != {market_meta.get('name')!r}",
                problems,
            )
            _expect(
                market.get("version") == version,
                f"marketplace.json: version != VERSION ({version})",
                problems,
            )
            plugins = market.get("plugins") or []
            _expect(len(plugins) == 1, "marketplace.json: expected exactly 1 plugin", problems)
            if plugins and isinstance(plugins[0], dict):
                _expect(
                    plugins[0].get("version") == version,
                    f"marketplace.json: plugin version != VERSION ({version})",
                    problems,
                )
                source = plugins[0].get("source") or {}
                _expect(
                    isinstance(source, dict) and source.get("source") == "git-subdir",
                    "marketplace.json: plugin source must be the git-subdir form",
                    problems,
                )
                _expect(
                    isinstance(source, dict) and source.get("path") == market_meta.get("plugin_path"),
                    f"marketplace.json: plugin source.path != {market_meta.get('plugin_path')!r}",
                    problems,
                )
                _expect(
                    isinstance(source, dict) and source.get("url") == market_meta.get("repo"),
                    f"marketplace.json: plugin source.url != {market_meta.get('repo')!r}",
                    problems,
                )

    server_raw = files.get(SERVER_JSON_PATH)
    if server_raw is None:
        problems.append("server.json is not planned by plan_outputs()")
    else:
        server = _load_json(server_raw, SERVER_JSON_PATH.name, problems)
        if isinstance(server, dict):
            _expect(
                server.get("$schema") == SERVER_SCHEMA,
                f"server.json: $schema != {SERVER_SCHEMA}",
                problems,
            )
            _expect(
                server.get("version") == version,
                f"server.json: version != VERSION ({version})",
                problems,
            )
            name = server.get("name") or ""
            _expect(
                bool(_SERVER_NAME_RE.match(name)) and name.count("/") == 1,
                f"server.json: name {name!r} violates the registry pattern",
                problems,
            )
            description = server.get("description") or ""
            _expect(
                1 <= len(description) <= 100,
                f"server.json: description length {len(description)} outside 1..100",
                problems,
            )
            repository = server.get("repository") or {}
            _expect(
                bool(repository.get("url")) and repository.get("source") == "github",
                "server.json: repository requires url + source 'github'",
                problems,
            )
            remotes = server.get("remotes") or []
            _expect(bool(remotes), "server.json: at least one remote is required", problems)
            if remotes and isinstance(remotes[0], dict):
                remote = remotes[0]
                _expect(
                    remote.get("type") == "streamable-http" and bool(remote.get("url")),
                    "server.json: remote requires type 'streamable-http' + url",
                    problems,
                )
                variables = remote.get("variables") or {}
                if "{host}" in (remote.get("url") or ""):
                    host_variable = variables.get("host") or {}
                    _expect(
                        host_variable.get("isRequired") is True,
                        "server.json: {host} URL requires variables.host.isRequired",
                        problems,
                    )
                headers = remote.get("headers") or []
                _expect(
                    any(
                        isinstance(header, dict) and header.get("name") == "X-API-Key"
                        for header in headers
                    ),
                    "server.json: remote must carry the X-API-Key header",
                    problems,
                )
            # #1913: the legacy SSE transport must be published as a second
            # remote with an explicit deprecation statement when the registry
            # declares it.
            legacy_path = (registry.get("store", {}).get("mcp_registry") or {}).get(
                "legacy_remote_path"
            )
            if legacy_path:
                legacy = remotes[1] if len(remotes) > 1 else {}
                _expect(
                    legacy.get("type") == "sse"
                    and legacy.get("url") == f"https://{{host}}{legacy_path}",
                    "server.json: second remote must be the legacy SSE transport",
                    problems,
                )
                legacy_host = (legacy.get("variables") or {}).get("host") or {}
                legacy_note = legacy_host.get("description") or ""
                _expect(
                    "DEPRECATED" in legacy_note and "/mcp/" in legacy_note,
                    "server.json: legacy SSE remote needs a deprecation note",
                    problems,
                )
            _expect(
                "<host>" not in server_raw,
                "server.json: legacy <host> placeholder remains",
                problems,
            )
            _expect(
                "reqlo_" not in server_raw,
                "server.json embeds a literal reqlo_ key",
                problems,
            )
    return problems


def _load_json(raw: str, label: str, problems: list[str]) -> Any:
    try:
        return json.loads(raw)
    except json.JSONDecodeError as exc:
        problems.append(f"{label}: invalid JSON: {exc}")
        return None


_HEADING_RE = re.compile(r"^#{1,6} ", re.MULTILINE)
_FENCE_RE = re.compile(r"^```", re.MULTILINE)


def check_parity(files: dict[Path, str]) -> list[str]:
    """German/English pages must have identical headings and code-block counts."""
    problems: list[str] = []
    for client_id in (*CLIENT_IDS, "capabilities"):
        de = files.get(DOCS_DIR / f"{client_id}.de.md", "")
        en = files.get(DOCS_DIR / f"{client_id}.md", "")
        if len(_HEADING_RE.findall(de)) != len(_HEADING_RE.findall(en)):
            problems.append(f"{client_id}: DE/EN heading count differs")
        if len(_FENCE_RE.findall(de)) != len(_FENCE_RE.findall(en)):
            problems.append(f"{client_id}: DE/EN code-block count differs")
    return problems


def check_stage2_parity(docs_dir: Path = DOCS_DIR) -> list[str]:
    """The hand-written Stufe-2 draft note keeps DE/EN heading/fence parity."""
    en_path = docs_dir / "STAGE2.md"
    de_path = docs_dir / "STAGE2.de.md"
    if not (en_path.is_file() and de_path.is_file()):
        return []
    en = en_path.read_text(encoding="utf-8")
    de = de_path.read_text(encoding="utf-8")
    problems: list[str] = []
    if len(_HEADING_RE.findall(en)) != len(_HEADING_RE.findall(de)):
        problems.append("STAGE2: DE/EN heading count differs")
    if len(_FENCE_RE.findall(en)) != len(_FENCE_RE.findall(de)):
        problems.append("STAGE2: DE/EN code-block count differs")
    return problems


def plan_outputs(registry: dict[str, Any]) -> dict[Path, str]:
    version = load_version()
    registry["clients"] = [
        {**client, "__conventions": registry["conventions"]}
        for client in registry["clients"]
    ]
    files: dict[Path, str] = {}
    for client in registry["clients"]:
        files[DOCS_DIR / f"{client['id']}.md"] = render_client(client, lang="en")
        files[DOCS_DIR / f"{client['id']}.de.md"] = render_client(client, lang="de")
    files[DOCS_DIR / "README.md"] = render_matrix(registry, lang="en")
    files[DOCS_DIR / "README.de.md"] = render_matrix(registry, lang="de")
    files[DOCS_DIR / "capabilities.md"] = render_capabilities(registry, lang="en")
    files[DOCS_DIR / "capabilities.de.md"] = render_capabilities(registry, lang="de")
    files[MARKETPLACE_PATH] = render_marketplace(registry, version)
    files[SERVER_JSON_PATH] = render_server_json(registry, version)
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero if artifacts are stale or invalid",
    )
    args = parser.parse_args(argv)

    registry = load_registry()
    cap_problems = validate_capabilities(registry)
    if cap_problems:
        # The capability page cannot be rendered from an invalid section.
        for problem in cap_problems:
            print(f"ERROR: {problem}", file=sys.stderr)
        return 1
    problems = validate_artifacts(registry)
    files = plan_outputs(registry)
    problems += validate_store_artifacts(registry, files)
    problems += check_parity(files)
    problems += check_stage2_parity()

    stale: list[str] = []
    for path, content in files.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != content:
            stale.append(path.relative_to(REPO_ROOT).as_posix())

    if args.check:
        for problem in problems:
            print(f"ERROR: {problem}", file=sys.stderr)
        for path in stale:
            print(f"STALE: {path} (run scripts/clients/render.py)", file=sys.stderr)
        if problems or stale:
            return 1
        print(f"OK: {len(files)} client/store artifacts up to date")
        return 0

    if problems:
        for problem in problems:
            print(f"ERROR: {problem}", file=sys.stderr)
        return 1

    written = 0
    for path, content in files.items():
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        written += 1
    print(f"wrote {written} of {len(files)} artifacts ({len(files) - written} unchanged)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
