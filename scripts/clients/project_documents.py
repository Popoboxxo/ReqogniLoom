#!/usr/bin/env python3
"""Project ReqogniLoom documents into a repository (Phase G / #1374 S3).

The server renders and compares; this script is the delivery half. It never
runs on ``main``/``master`` and never overwrites a file that changed on disk
behind Loom's back.

Usage::

    python scripts/clients/project_documents.py \
        --url https://reqogniloom.example/mcp/ \
        --key-env REQOGNILOOM_API_KEY \
        --workspace <uuid> --repo . --check
    # or --write, which writes loom_changed/missing files on the current branch

Exit codes: ``0`` everything in sync, ``1`` deviation/conflict (nothing
overwritten), ``2`` usage/transport/branch error.

Stdlib only; the JSON-RPC helper is deliberately local (no import of
``mcp_probe``), so the script can ship into a consuming repository on its own.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any, Callable

MCP_PROTOCOL_VERSION = "2025-06-18"
CLIENT_INFO = {"name": "reqogniloom-project-documents", "version": "1"}
WRITE_STATES = frozenset({"loom_changed", "missing_in_repo"})
BLOCKING_STATES = frozenset({"file_changed", "conflict", "untracked_in_loom"})

_HEADER_RE = re.compile(
    r"\A<!-- GENERATED by ReqogniLoom.*?-->\r?\n\r?\n", re.DOTALL
)


def strip_generated_header(text: str) -> str:
    """Return the content the server hashed (everything after the header)."""
    return _HEADER_RE.sub("", text, count=1)


def content_sha256(text: str) -> str:
    """SHA-256 of the file content *without* the generated header."""
    return hashlib.sha256(strip_generated_header(text).encode("utf-8")).hexdigest()


def safe_target(repo: Path, relative: str) -> Path | None:
    """Resolve *relative* inside *repo*; ``None`` when it would escape."""
    if not relative or relative.startswith(("/", "\\")):
        return None
    candidate = (repo / relative).resolve()
    try:
        candidate.relative_to(repo.resolve())
    except ValueError:
        return None
    return candidate


def current_branch(repo: Path) -> str:
    result = subprocess.run(
        ["git", "rev-parse", "--abbrev-ref", "HEAD"],
        cwd=repo,
        capture_output=True,
        text=True,
        check=False,
    )
    return result.stdout.strip() if result.returncode == 0 else ""


class McpClient:
    """Minimal JSON-RPC client: initialize once, then ``tools/call``."""

    def __init__(self, url: str, api_key: str, timeout: float = 30.0) -> None:
        self.url = url
        self.api_key = api_key
        self.timeout = timeout
        self._initialized = False

    def _post(self, frame: dict[str, Any]) -> dict[str, Any]:
        request = urllib.request.Request(
            self.url,
            data=json.dumps(frame).encode("utf-8"),
            method="POST",
            headers={
                "Content-Type": "application/json",
                "Accept": "application/json, text/event-stream",
                "X-API-Key": self.api_key,
            },
        )
        try:
            with urllib.request.urlopen(request, timeout=self.timeout) as response:
                return json.loads(response.read().decode("utf-8"))
        except urllib.error.HTTPError as exc:
            raise RuntimeError(f"MCP HTTP {exc.code}: {exc.read()[:300]!r}") from exc

    def _initialize(self) -> None:
        if self._initialized:
            return
        frame = self._post(
            {
                "jsonrpc": "2.0",
                "id": 1,
                "method": "initialize",
                "params": {
                    "protocolVersion": MCP_PROTOCOL_VERSION,
                    "capabilities": {},
                    "clientInfo": CLIENT_INFO,
                },
            }
        )
        if "result" not in frame:
            raise RuntimeError(f"initialize failed: {frame.get('error')}")
        self._initialized = True

    def call_tool(self, name: str, params: dict[str, Any]) -> dict[str, Any]:
        self._initialize()
        frame = self._post(
            {
                "jsonrpc": "2.0",
                "id": 2,
                "method": "tools/call",
                "params": {"name": name, "arguments": params},
            }
        )
        if "error" in frame:
            raise RuntimeError(f"{name} failed: {frame['error']}")
        result = frame.get("result") or {}
        if result.get("isError"):
            raise RuntimeError(f"{name} returned an error: {result}")
        return result.get("structuredContent") or result.get("content") or result


def run(
    *,
    repo: Path,
    workspace: str,
    mode: str,
    rpc: Callable[[str, dict[str, Any]], dict[str, Any]],
    out=sys.stdout,
    err=sys.stderr,
) -> int:
    """Execute one check/write pass. Returns the process exit code."""
    try:
        listing = rpc(
            "document.projection_status", {"workspace_id": workspace, "files": {}}
        )
        rows = listing.get("documents") or []
        local: dict[str, str] = {}
        for row in rows:
            target = safe_target(repo, str(row.get("path") or ""))
            if target is None:
                print(f"refusing unsafe path: {row.get('path')}", file=err)
                return 2
            if target.is_file():
                local[str(row["path"])] = content_sha256(
                    target.read_text(encoding="utf-8")
                )
        status = rpc(
            "document.projection_status",
            {"workspace_id": workspace, "files": local},
        )
    except Exception as exc:  # noqa: BLE001 - transport/usage failure is exit 2
        print(f"error: {exc}", file=err)
        return 2

    exit_code = 0
    for row in status.get("documents") or []:
        state = str(row.get("state"))
        path = str(row.get("path"))
        document_id = str(row.get("document_id"))
        if state == "in_sync":
            print(f"in sync: {path}", file=out)
            continue
        if state in BLOCKING_STATES:
            print(f"{state}: {path} — not overwritten", file=err)
            exit_code = 1
            continue

        print(f"{state}: {path}", file=out)
        if mode != "write":
            exit_code = 1
            continue

        target = safe_target(repo, path)
        if target is None:
            print(f"refusing unsafe path: {path}", file=err)
            return 2
        try:
            projection = rpc("document.project", {"id": document_id})
            content = str(projection["content"])
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
            sha256 = content_sha256(content)
            rpc(
                "document.projection_status",
                {
                    "workspace_id": workspace,
                    "files": {**local, path: sha256},
                    "confirm": {"document_id": document_id, "sha256": sha256},
                },
            )
        except Exception as exc:  # noqa: BLE001 - one failed write is exit 2
            print(f"write failed for {path}: {exc}", file=err)
            return 2
        if sha256 != str(projection.get("sha256")):
            print(f"hash mismatch after writing {path}", file=err)
            return 1
        print(f"wrote {path}", file=out)
    return exit_code


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", required=True, help="MCP endpoint, e.g. https://host/mcp/")
    parser.add_argument("--key-env", default="REQOGNILOOM_API_KEY")
    parser.add_argument("--workspace", required=True)
    parser.add_argument("--repo", default=".")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_const", const="check", dest="mode")
    group.add_argument("--write", action="store_const", const="write", dest="mode")
    args = parser.parse_args(argv)
    args.mode = args.mode or "check"

    repo = Path(args.repo).resolve()
    branch = current_branch(repo)
    if branch in ("main", "master"):
        print(
            f"refusing to project on '{branch}': create a feature branch first",
            file=sys.stderr,
        )
        return 2
    if not branch:
        print("not a git repository (or detached HEAD)", file=sys.stderr)
        return 2

    api_key = os.environ.get(args.key_env, "")
    if not api_key:
        print(f"missing API key in ${args.key_env}", file=sys.stderr)
        return 2

    client = McpClient(args.url, api_key)
    return run(
        repo=repo,
        workspace=args.workspace,
        mode=args.mode,
        rpc=client.call_tool,
    )


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
