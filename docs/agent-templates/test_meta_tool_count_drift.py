"""Fails CI the moment the MCP tool count documented in the root context files
drifts from the authoritative number in the committed tool manifest.

What it guards
--------------
``docs/agent-templates/tool-manifest.json`` is the single source of truth for
the MCP surface: it is regenerated via ``manage.py export_tool_manifest`` and is
what every other gate (``backend/mcp_server/tests/test_tool_manifest_drift.py``,
the plugin generators under ``dist/``, the shipped agent templates) reads. Three
files document that count as plain prose:

* ``.meta-config/project.yaml`` — the agent-meta *source* (the only place a
  number in the managed block can be corrected),
* ``AGENTS.md`` and ``CLAUDE.md`` — generated artefacts of that source.

Why it exists (issue #1104)
---------------------------
The agent-meta-managed block in AGENTS.md/CLAUDE.md is rendered from
``.meta-config/project.yaml``; a hand edit of the generated file is silently
overwritten by the next ``.agent-meta/scripts/sync.py`` run. That is exactly how
``227`` survived in the root context while the manifest already carried
``tool_count: 228``: every consumer downstream of the generated files (agent
prompts, skills, plugin allowlists) inherited the stale count and nothing went
red. This gate closes that hole as a ratchet — it fails on ANY mismatch in
either direction and names the fix.

Extraction rule (deliberately narrow, documented so it can be reviewed)
----------------------------------------------------------------------
A statement documents a tool count only when BOTH hold:

1. it contains a number immediately followed by optional whitespace and the
   word ``Tools`` (``TOOL_COUNT_RE`` = ``(\\d+)\\s+Tools``) — "227 Tools",
   "228 Tools in 36 Gruppen"; and
2. one of the catalog markers ``Tool-Gruppen-Präfix``, ``Tool-Registry`` or
   ``MCP-Katalog`` (``TOOL_COUNT_MARKERS_RE``) appears within
   ``TOOL_COUNT_CONTEXT_WINDOW`` characters in front of it.

The marker requirement is what keeps unrelated "N Tools" sentences — group-level
counts such as "Group 1: Requirements (11 Tools)", or family counts such as
"``ai_derivation.*`` (6 Tools)" — from being read as a second, conflicting
catalog size. Every real occurrence in the guarded files is shaped
"… Tool-Gruppen-Präfixe, 228 Tools", "… MCP-Tool-Registry: 228 Tools …" or
"… MCP-Katalog 228 Tools …", so the rule matches them and nothing else. Note
that "36 Tool-Gruppen-Präfixe" itself never matches rule 1: there the digits are
followed by "Tool-", not by "Tools".

YAML files are parsed *before* matching (``documented_tool_counts_in_yaml``):
two of the five project.yaml occurrences wrap across source lines
("… Tool-Gruppen-Präfixe, 227\\n    Tools)") and only the parser folds them
back into "227 Tools".

Dependencies: stdlib + PyYAML only — the CI job that runs this
(``agent-templates-test``) installs nothing else. No Django, no repo imports.

Run it
------
    python -m pytest docs/agent-templates/test_meta_tool_count_drift.py -q
    # exactly as CI does (job "agent-templates-test"):
    pytest docs/agent-templates dist
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Dict, Iterable, List, Mapping, Optional, Set

import yaml

#: Repo-relative path of the authoritative tool manifest. This guard only ever
#: READS it — it is regenerated by ``manage.py export_tool_manifest``.
MANIFEST_REL = "docs/agent-templates/tool-manifest.json"

#: The agent-meta source of the generated root-context files. A wrong number
#: here is the one that must be corrected (editing AGENTS.md/CLAUDE.md directly
#: is pointless — the next sync overwrites it, see module docstring).
PROJECT_YAML_REL = ".meta-config/project.yaml"

#: Generated root-context artefacts (``.agent-meta/scripts/sync.py`` output).
#: Guarded as well so that the count cannot silently diverge between source
#: and rendered files.
AGENTS_MD_REL = "AGENTS.md"
CLAUDE_MD_REL = "CLAUDE.md"

#: Every file this guard ties to the manifest's ``tool_count``, in report order.
DOCUMENTED_FILES = (PROJECT_YAML_REL, AGENTS_MD_REL, CLAUDE_MD_REL)

#: A documented tool count is a number that *immediately* precedes the word
#: "Tools" ("227 Tools", "228 Tools in 36 Gruppen"). A group count such as
#: "36 Tool-Gruppen-Präfixe" never matches — there the digits are followed by
#: "Tool-", not by "Tools".
TOOL_COUNT_RE = re.compile(r"(\d+)\s+Tools\b")

#: A "N Tools" phrase only names the *MCP catalog size* when one of these
#: catalog markers sits right in front of it. They are the three shapes every
#: real occurrence uses: "… Tool-Gruppen-Präfixe, 228 Tools",
#: "… MCP-Tool-Registry: 228 Tools …", "… MCP-Katalog 228 Tools …". The marker
#: requirement keeps unrelated "N Tools" sentences ("Group 1: Requirements
#: (11 Tools)", "ai_derivation.* (6 Tools)") from being read as a second,
#: conflicting catalog size.
TOOL_COUNT_MARKERS_RE = re.compile(r"Tool-Gruppen-Präfix|Tool-Registry|MCP-Katalog")

#: How far in front of a "N Tools" match a catalog marker may sit. 80 chars
#: comfortably covers the longest real phrasing ("36 Tool-Gruppen-Präfixen und
#: 228 Tools") without reaching into a neighbouring statement.
TOOL_COUNT_CONTEXT_WINDOW = 80


def _statement_counts(statement: str) -> Set[int]:
    """Return the MCP tool counts documented in a single statement.

    A statement is one line of a markdown file, resp. one line of a parsed
    (and therefore line-folded) YAML string value.
    """
    counts: Set[int] = set()
    for match in TOOL_COUNT_RE.finditer(statement):
        window = statement[max(0, match.start() - TOOL_COUNT_CONTEXT_WINDOW):match.start()]
        if TOOL_COUNT_MARKERS_RE.search(window):
            counts.add(int(match.group(1)))
    return counts


def documented_tool_counts(text: str) -> Set[int]:
    """Return all MCP tool counts documented in a plain-text document."""
    counts: Set[int] = set()
    for line in text.splitlines():
        counts |= _statement_counts(line)
    return counts


def _iter_string_values(node: object) -> Iterable[str]:
    """Yield every string value in a parsed YAML tree (dicts and lists included)."""
    if isinstance(node, str):
        yield node
    elif isinstance(node, dict):
        for value in node.values():
            yield from _iter_string_values(value)
    elif isinstance(node, list):
        for item in node:
            yield from _iter_string_values(item)


def documented_tool_counts_in_yaml(text: str) -> Set[int]:
    """Return all MCP tool counts documented anywhere inside a YAML document.

    The text is parsed first: two of the five project.yaml occurrences wrap
    across source lines ("… Tool-Gruppen-Präfixe, 227\\n    Tools)") and only
    the parser folds them back into "227 Tools".
    """
    data = yaml.safe_load(text)
    counts: Set[int] = set()
    for value in _iter_string_values(data):
        for line in str(value).splitlines():
            counts |= _statement_counts(line)
    return counts


def check_documented(manifest_count: int, files: Mapping[str, str]) -> List[str]:
    """Compare a manifest tool count against explicit file contents.

    ``files`` maps a repo-relative path (one of ``DOCUMENTED_FILES``) to its
    text; a ``.yaml``/``.yml`` suffix selects the YAML extraction, everything
    else the markdown one. Returns one full-sentence problem per offending
    file; an empty list means green.
    """
    problems: List[str] = []
    for rel_path in DOCUMENTED_FILES:
        if rel_path not in files:
            problems.append(
                f"{rel_path} was not supplied to check_documented() — the guard "
                "cannot confirm the documented MCP tool count without its text; "
                "pass it in."
            )
            continue
        text = files[rel_path]
        if rel_path.endswith((".yaml", ".yml")):
            found = documented_tool_counts_in_yaml(text)
        else:
            found = documented_tool_counts(text)
        if not found:
            problems.append(
                f"{rel_path} documents no MCP tool count at all (no "
                f"\"<int> Tools\" phrase preceded by a catalog marker) — add the "
                f"current count ({manifest_count}) to {rel_path}, or drop it from "
                "DOCUMENTED_FILES if it no longer documents the MCP surface "
                "(a conscious, reviewed decision)."
            )
            continue
        wrong = sorted(found - {manifest_count})
        if wrong:
            problems.append(
                f"{rel_path} documents tool count {wrong}, but {MANIFEST_REL} "
                f"says tool_count = {manifest_count} — update the number(s) in "
                f"{rel_path} to {manifest_count}; if the manifest is the stale "
                "side instead, regenerate it with "
                "`python backend/manage.py export_tool_manifest` and commit both."
            )
    return problems


def _find_repo_root() -> Optional[Path]:
    """Locate the repo root by walking up from this file, or return None.

    Mirrors the ancestor-walk in
    ``backend/mcp_server/tests/test_tool_manifest_drift.py``: a fixed
    ``parents[N]`` index breaks when the file runs from another layout (host
    checkout vs. container mount), so walk until the manifest turns up.
    """
    for ancestor in Path(__file__).resolve().parents:
        if (ancestor / MANIFEST_REL).is_file():
            return ancestor
    return None


def find_drift(root: Optional[Path] = None) -> List[str]:
    """Return one problem per artefact whose documented tool count drifted.

    An empty list means: the manifest is readable and carries an integer
    ``tool_count``, and every guarded file documents exactly that count.
    """
    if root is None:
        root = _find_repo_root()
        if root is None:
            return [
                f"repo root not reachable from {Path(__file__).resolve()} — no "
                f"ancestor directory contains {MANIFEST_REL}; run the guard from "
                "inside the repository (or mount docs/ in the container)."
            ]
    root = Path(root)
    problems: List[str] = []

    manifest_path = root / MANIFEST_REL
    if not manifest_path.is_file():
        problems.append(
            f"{MANIFEST_REL} is missing at {manifest_path} — the authoritative "
            "tool count cannot be read, so no documented number can be verified; "
            "restore the committed manifest."
        )
        return problems
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        problems.append(
            f"{MANIFEST_REL} is unreadable ({exc}) — the authoritative tool count "
            "cannot be determined; fix or restore the manifest."
        )
        return problems
    manifest_count = manifest.get("tool_count")
    if not isinstance(manifest_count, int):
        problems.append(
            f"{MANIFEST_REL} has no integer tool_count (found "
            f"{manifest_count!r}) — regenerate it with "
            "`python backend/manage.py export_tool_manifest`."
        )
        return problems

    files: Dict[str, str] = {}
    for rel_path in DOCUMENTED_FILES:
        path = root / rel_path
        if not path.is_file():
            problems.append(
                f"{rel_path} is missing at {path} — this guard verifies that the "
                "documented tool count matches the manifest, but the file does not "
                f"exist; restore it (it is generated from {PROJECT_YAML_REL} by "
                ".agent-meta/scripts/sync.py)."
            )
            continue
        files[rel_path] = path.read_text(encoding="utf-8")
    problems.extend(check_documented(manifest_count, files))
    return problems


def test_repo_documents_the_manifest_tool_count() -> None:
    """The real repository must be consistent (the positive gate)."""
    drift = find_drift()
    assert not drift, (
        "The documented MCP tool count drifted from "
        f"{MANIFEST_REL}: {drift} — correct the number at the source "
        f"({PROJECT_YAML_REL}) and regenerate AGENTS.md/CLAUDE.md with "
        "`python .agent-meta/scripts/sync.py`."
    )


def test_stale_documented_count_goes_red(tmp_path: Path) -> None:
    """NEGATIVE proof: a stale documented count must make the gate go RED.

    Mirrors the issue #1104 situation (manifest 228 vs. documented 227) with a
    synthetic 999-vs-227 pair. All files are written inside ``tmp_path``, never
    inside the repository.
    """
    (tmp_path / "docs" / "agent-templates").mkdir(parents=True)
    (tmp_path / MANIFEST_REL).write_text(
        json.dumps({"generated_from": "synthetic", "tool_count": 999, "tools": []}),
        encoding="utf-8",
    )
    (tmp_path / PROJECT_YAML_REL).parent.mkdir(parents=True, exist_ok=True)
    # The wrap across lines is intentional: it exercises the YAML folding.
    (tmp_path / PROJECT_YAML_REL).write_text(
        "variables:\n"
        "  PROJECT_DESCRIPTION: AI-natives Requirements- und Test-Management-Tool\n"
        "    mit nativem MCP Server (36 Tool-Gruppen-Präfixe, 227\n"
        "    Tools), LLM-Adapter und i18n.\n",
        encoding="utf-8",
    )
    (tmp_path / AGENTS_MD_REL).write_text(
        "- MCP-Server (JSON-RPC 2.0) mit 36 Tool-Gruppen-Präfixen und 227 Tools "
        "für AI-Integration.\n",
        encoding="utf-8",
    )
    (tmp_path / CLAUDE_MD_REL).write_text(
        "**Beschreibung:** … nativem MCP Server (36 Tool-Gruppen-Präfixe, "
        "227 Tools) …\n",
        encoding="utf-8",
    )

    drift = find_drift(tmp_path)
    assert drift, (
        "The gate stayed GREEN although all documented files say 227 while the "
        "manifest says tool_count = 999 — the drift check does not fire; "
        "investigate documented_tool_counts()/find_drift()."
    )
    assert any("227" in problem and "999" in problem for problem in drift), (
        f"The gate went RED, but not with the expected 227-vs-999 comparison: "
        f"{drift}"
    )


def test_missing_documented_count_fails() -> None:
    """A documented file that carries no tool count at all must fail, too."""
    drift = check_documented(
        999,  # synthetic manifest count — the gate never hardcodes the real one.
        {
            PROJECT_YAML_REL: "variables:\n  PROJECT_NAME: ReqogniLoom\n",
            AGENTS_MD_REL: "# Agents\n\nNo tool count documented here.\n",
            CLAUDE_MD_REL: "# Claude\n\nNo tool count documented here.\n",
        },
    )
    assert len(drift) == len(DOCUMENTED_FILES), (
        f"Expected one problem per documented file, got: {drift}"
    )
    assert all(
        rel_path in problem and "no MCP tool count" in problem
        for problem, rel_path in zip(drift, DOCUMENTED_FILES)
    ), f"The problems do not name file and cause as expected: {drift}"


def test_unrelated_tool_phrases_are_not_tool_counts() -> None:
    """The marker rule must not read unrelated "N Tools" sentences as counts."""
    text = (
        "Group 1: Requirements (11 Tools)\n"
        "Nur `ai_derivation.*` (6 Tools) ist eine Einzelfamilie.\n"
        "MCP-Server (JSON-RPC 2.0) mit 36 Tool-Gruppen-Präfixen und 228 Tools "
        "für AI-Integration.\n"
    )
    assert documented_tool_counts(text) == {228}, (
        "Only the catalog count is a documented tool count; group-level and "
        f"family-level counts must be ignored, got {documented_tool_counts(text)}."
    )


def test_unusable_manifest_fails(tmp_path: Path) -> None:
    """An unreadable manifest or a missing tool_count must fail, not skip."""
    (tmp_path / "docs" / "agent-templates").mkdir(parents=True)
    (tmp_path / MANIFEST_REL).write_text("{ not json", encoding="utf-8")
    assert find_drift(tmp_path), (
        "A corrupt manifest must produce a drift problem, but find_drift() "
        "stayed silent."
    )

    (tmp_path / MANIFEST_REL).write_text(
        json.dumps({"tools": []}), encoding="utf-8"
    )
    drift = find_drift(tmp_path)
    assert drift and "tool_count" in drift[0], (
        "A manifest without tool_count must produce a drift problem, got: "
        f"{drift}"
    )
