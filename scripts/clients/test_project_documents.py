"""Phase G / #1374 S3: the projection CLI (check/write, branch guard)."""

from __future__ import annotations

import io
from pathlib import Path

import pytest

import project_documents as cli

WORKSPACE = "ws-1"
PATH = "docs/superpowers/specs/spec.md"
CONTENT = "<!-- GENERATED by ReqogniLoom — do not edit.\n     hash abc -->\n\n# Spec\n"
SHA = cli.content_sha256(CONTENT)


def _rpc(*, state="loom_changed", repo_state="loom_changed", calls=None):
    seen = {"status": 0}

    def rpc(name, params):
        if calls is not None:
            calls.append((name, params))
        if name == "document.projection_status":
            seen["status"] += 1
        if name == "document.projection_status" and seen["status"] == 1:
            return {"documents": [{"document_id": "d1", "path": PATH, "state": state}]}
        if name == "document.projection_status":
            return {
                "documents": [
                    {
                        "document_id": "d1",
                        "path": PATH,
                        "state": repo_state,
                        "projected_sha256": SHA,
                        "current_sha256": params.get("files", {}).get(PATH, ""),
                    }
                ]
            }
        if name == "document.project":
            return {"content": CONTENT, "sha256": SHA, "path": PATH}
        raise AssertionError(name)

    return rpc


def _repo(tmp_path: Path) -> Path:
    (tmp_path / "docs/superpowers/specs").mkdir(parents=True)
    return tmp_path


def test_check_mode_reports_loom_changed_with_exit_1(tmp_path) -> None:
    out, err = io.StringIO(), io.StringIO()

    code = cli.run(
        repo=_repo(tmp_path), workspace=WORKSPACE, mode="check", rpc=_rpc(), out=out, err=err
    )

    assert code == 1
    assert "loom_changed" in out.getvalue()


def test_write_mode_writes_only_loom_changed_files(tmp_path) -> None:
    repo = _repo(tmp_path)
    calls = []

    code = cli.run(
        repo=repo,
        workspace=WORKSPACE,
        mode="write",
        rpc=_rpc(calls=calls),
        out=io.StringIO(),
        err=io.StringIO(),
    )

    assert code == 0
    assert (repo / PATH).read_text(encoding="utf-8") == CONTENT
    assert cli.content_sha256((repo / PATH).read_text(encoding="utf-8")) == SHA
    confirm = [p for n, p in calls if n == "document.projection_status" and p.get("confirm")]
    assert confirm and confirm[-1]["confirm"]["sha256"] == SHA


def test_file_changed_is_never_overwritten(tmp_path) -> None:
    repo = _repo(tmp_path)
    target = repo / PATH
    target.write_text("handedit", encoding="utf-8")

    code = cli.run(
        repo=repo,
        workspace=WORKSPACE,
        mode="write",
        rpc=_rpc(repo_state="file_changed"),
        out=io.StringIO(),
        err=io.StringIO(),
    )

    assert code == 1
    assert target.read_text(encoding="utf-8") == "handedit"


def test_conflict_blocks_the_write(tmp_path) -> None:
    repo = _repo(tmp_path)

    code = cli.run(
        repo=repo,
        workspace=WORKSPACE,
        mode="write",
        rpc=_rpc(repo_state="conflict"),
        out=io.StringIO(),
        err=io.StringIO(),
    )

    assert code == 1
    assert not (repo / PATH).exists()


def test_in_sync_is_exit_0(tmp_path) -> None:
    code = cli.run(
        repo=_repo(tmp_path),
        workspace=WORKSPACE,
        mode="check",
        rpc=_rpc(repo_state="in_sync"),
        out=io.StringIO(),
        err=io.StringIO(),
    )

    assert code == 0


def test_a_path_escape_is_refused(tmp_path, monkeypatch) -> None:
    rpc = _rpc()
    original = rpc

    def escaping(name, params):
        result = original(name, params)
        for row in result.get("documents", []):
            row["path"] = "../outside.md"
        return result

    code = cli.run(
        repo=_repo(tmp_path),
        workspace=WORKSPACE,
        mode="write",
        rpc=escaping,
        out=io.StringIO(),
        err=io.StringIO(),
    )

    assert code == 2


def test_a_missing_key_is_exit_2(tmp_path, monkeypatch) -> None:
    monkeypatch.delenv("REQOGNILOOM_API_KEY", raising=False)
    monkeypatch.setattr(cli, "current_branch", lambda repo: "feat/x")

    code = cli.main(["--url", "http://x/mcp/", "--workspace", WORKSPACE, "--repo", str(tmp_path)])

    assert code == 2


def test_main_refuses_on_the_main_branch(tmp_path, monkeypatch) -> None:
    monkeypatch.setattr(cli, "current_branch", lambda repo: "main")
    monkeypatch.setenv("REQOGNILOOM_API_KEY", "k")

    code = cli.main(["--url", "http://x/mcp/", "--workspace", WORKSPACE, "--repo", str(tmp_path)])

    assert code == 2


def test_content_hash_ignores_the_generated_header() -> None:
    with_header = "<!-- GENERATED by ReqogniLoom — do not edit.\n     x -->\n\n# Body\n"
    without = "# Body\n"

    assert cli.content_sha256(with_header) == cli.content_sha256(without)
