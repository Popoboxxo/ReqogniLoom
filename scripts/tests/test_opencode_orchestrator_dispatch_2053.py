"""Issue #2053 guard for the generated OpenCode orchestrator prompt.

``.opencode/`` is generated by agent-meta from the submodule template and is
gitignored, so this guard reads whatever is present locally instead of pinning
a copy of the prompt. It asserts that the generated dispatch sections:

* never use the Claude/Gemini-only ``task(subagent_type=...)`` tool,
* never call ``route_intent`` (the JSON definition is data only),
* dispatch via ``subagent(agent=<name>, ...)`` with roles resolved from
  ``routing.rules`` / ``name_index``,
* never target the harness ``general`` built-in or the ``orchestrator`` itself,
* fail closed to ``main_chat`` when a named role is unavailable.

When the generated prompt is absent (CI jobs without agent-meta sync) the guard
skips with an explicit reason. CI wiring: add this file to the explicit pytest
file list in ``.github/workflows/ci.yml`` next to
``scripts/tests/test_normative_path_refs.py`` (separate change; ``.github/`` is
outside this fix's write set).
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

# scripts/tests/<file>.py -> parents[2] is the repository root.
REPO_ROOT = Path(__file__).resolve().parents[2]
ORCHESTRATOR = REPO_ROOT / ".opencode" / "agents" / "orchestrator.md"
PIPELINE_DIR = REPO_ROOT / ".opencode" / "pipeline-details"

# A call to the Claude/Gemini dispatch tool, its parameter name, or an invented
# route_intent() call. Plain mentions (the JSON data block, the "no native
# route_intent tool" negation) are intentionally allowed.
FORBIDDEN_DISPATCH = re.compile(r"task\(|subagent_type|route_intent\s*\(")
CALL = re.compile(r'subagent\(\s*agent="([^"]+)"')
DATA_LINE_PREFIX = '{"tool":'
FORBIDDEN_ROLES = frozenset({"general", "orchestrator", "orchestrator-iteration", "se-orchestrator"})


def _prompts() -> dict[Path, str]:
    if not ORCHESTRATOR.exists():
        pytest.skip("generated OpenCode orchestrator prompt absent; run agent-meta sync")
    paths = [ORCHESTRATOR, *sorted(PIPELINE_DIR.glob("*.md"))]
    return {path: path.read_text(encoding="utf-8") for path in paths}


def _roster(orchestrator_text: str) -> set[str]:
    """The only authoritative role list: routing.rules + name_index (data)."""
    data_line = next(
        line for line in orchestrator_text.splitlines() if line.startswith(DATA_LINE_PREFIX)
    )
    routing = json.loads(data_line)["routing"]
    rules = {entry["agent"] for entry in routing["rules"]}
    index = {entry["agent"] for entry in routing["name_index"]}
    assert rules and index, "#2053: generated routing data is empty"
    return rules | index


def test_no_claude_or_route_intent_dispatch_syntax() -> None:
    offenders: dict[str, list[str]] = {}
    for path, text in _prompts().items():
        hits = FORBIDDEN_DISPATCH.findall(text)
        if hits:
            offenders[str(path.relative_to(REPO_ROOT))] = hits
    assert not offenders, f"#2053: forbidden dispatch syntax reintroduced: {offenders}"


def test_route_intent_only_as_data_or_negation() -> None:
    text = _prompts()[ORCHESTRATOR]
    bad = [
        line[:160]
        for line in text.splitlines()
        if not line.startswith(DATA_LINE_PREFIX)
        and "route_intent" in line
        and not ("kein" in line.lower() and "natives" in line.lower())
    ]
    assert not bad, f"#2053: route_intent used outside the data/negation line: {bad}"


def test_dispatches_use_subagent_with_known_roles() -> None:
    prompts = _prompts()
    roster = _roster(prompts[ORCHESTRATOR])
    called: set[str] = set()
    for path, text in prompts.items():
        names = CALL.findall(text)
        assert names, f"#2053: {path.name} has no subagent(agent=...) dispatch"
        called.update(names)

    # Placeholders such as <name> are fine in examples; concrete roles must
    # resolve against the generated routing data.
    concrete = {name for name in called if not name.startswith("<")}
    assert concrete, "#2053: no concrete subagent(agent=<role>) dispatch found"
    unknown = sorted(concrete - roster)
    assert not unknown, f"#2053: dispatch roles absent from routing.rules/name_index: {unknown}"
    assert not (called & FORBIDDEN_ROLES), (
        f"#2053: forbidden dispatch target: {sorted(called & FORBIDDEN_ROLES)}"
    )


def test_fail_closed_unavailable_role_escalates_to_main_chat() -> None:
    prompts = _prompts()
    for path, text in prompts.items():
        rel = str(path.relative_to(REPO_ROOT))
        assert "subagent" in text, f"{rel}: missing OpenCode dispatch tool"
        lowered = text.lower()
        assert "`general`" in text and ("verboten" in lowered or "kein harness" in lowered), (
            f"{rel}: harness general built-in not explicitly forbidden"
        )
        assert "main_chat" in text and "Eskalation" in text, (
            f"{rel}: missing main_chat escalation"
        )
        assert "verfügbar" in text.lower(), f"{rel}: missing unavailable-role trigger"
    orch = prompts[ORCHESTRATOR]
    assert "subagent(agent=" in orch, "#2053: orchestrator missing subagent dispatch syntax"
    assert "Fail-closed role resolution" in orch, "#2053: orchestrator missing fail-closed rule"
